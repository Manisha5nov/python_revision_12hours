'''
what is comparison operator in Python?
Comparison operators in Python are used to compare two values or expressions and return a boolean result (True or False).
They are commonly used in conditional statements and loops to control the flow of a program based on certain conditions. 
The comparison operators in Python include:
1. Equal to (==): Returns True if the values on both sides are equal.
2. Not equal to (!=): Returns True if the values on both sides are not equal.
3. Greater than (>): Returns True if the value on the left is greater than the value on the right.
4. Less than (<): Returns True if the value on the left is less than the value on the right.
5. Greater than or equal to (>=): Returns True if the value on the left is greater than or equal to the value on the right.
6. Less than or equal to (<=): Returns True if the value on the left is less than or equal to the value on the right.

'''
num1=int(input("Enter first number: "))
num2=int(input("Enter second number: "))
print("Equal to:", num1 == num2)
print("Not equal to:", num1 != num2)
print("Greater than:", num1 > num2)
print("Less than:", num1 < num2)
print("Greater than or equal to:", num1 >= num2)
print("Less than or equal to:", num1 <= num2)
