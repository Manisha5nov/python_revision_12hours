# Data Type in Python-
# Every value in Python has a data type. Some of the most common data types in Python include:
    
# 1. Numeric Types: These include integers (int), floating-point numbers (float), and complex numbers (complex). 
#    - Example: 
#      - int: 5, -3, 0
#      - float: 3.14, -2.5, 0.0
#      - complex: 2 + 3j, -1 - 4j
     
# 2. Sequence Types: These include strings (str), lists (list), and tuples (tuple).
#    - Example:
#      - str: "Hello, World!", 'Python'
#      - list: [1, 2, 3], ['apple', 'banana', 'cherry']
#      - tuple: (1, 2, 3), ('a', 'b', 'c')
     
# 3. Mapping Type: This includes dictionaries (dict), which are used to store key-value pairs.
#    - Example:
#      - dict: {'name': 'Alice', 'age': 30}, {'fruit': 'apple', 'color': 'red'}
     