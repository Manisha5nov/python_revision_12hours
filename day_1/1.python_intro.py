# what is python?
# python is a high-level, interpreted programming language known for its simplicity and readability. 
# It was created by Guido van Rossum and first released in 1991. Python supports multiple programming paradigms, 
# including procedural, object-oriented, and functional programming.

# where use python?
# Python is used in various fields and industries, including:
# 1. Web Development: Frameworks like Django and Flask are popular for building web applications.
# 2. Data Science and Machine Learning: Libraries like NumPy, pandas, and scikit-learn are widely used.
# 3. Automation and Scripting: Python is often used for writing scripts to automate repetitive tasks.

