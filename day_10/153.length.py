# How do you find the length of a string?
# You can find the length of a string in Python using the built-in `len()` function. 
# The `len()` function takes a string as an argument and returns the number of characters in that string, 
# including spaces and special characters. Here is an example:
string = "Hello, World!"    
length = len(string)
print("The length of the string is:", length)
