# What is negative indexing?
# Negative indexing in Python refers to accessing characters in a string using negative integer indices.
# The last character of the string is at index -1, the second last at index -2, and so on. This allows you to access
# characters from the end of the string without needing to know its length.
# For example, if you have a string `s = "Python"`, then `s[-1]` would return `'n'`, `s[-2]` would return `'o'`,
# and so forth.

