# What is string indexing?

# String indexing in Python refers to the process of accessing individual characters within a
# string using numerical indices. Strings are zero-indexed, meaning the first character is at index 0,
# the second at index 1, and so on. You can access a character at a specific index using square brackets `[]` 
# after the string variable name. For example, if you have a string `s = "Hello"`, then `s[0]` would return `'H'`, 
# `s[1]` would return `'e'`, and so forth.

