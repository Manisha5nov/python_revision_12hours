# type of operator in python
# 1. Arithmetic Operators: Used for mathematical operations like addition, subtraction, multiplication, division, etc
# 2. Comparison Operators: Used to compare values and return a boolean result (True or False).
# 3. Logical Operators: Used to combine conditional statements and return a boolean result.
# 4. Assignment Operators: Used to assign values to variables.
# 5. Bitwise Operators: Used to perform bitwise operations on integers.
# 6. Membership Operators: Used to test if a value is present in a sequence (like a list, tuple, or string).
# 7. Identity Operators: Used to compare the memory locations of two objects to determine if they are the same object in memory.  
# 8. Ternary Operator: A shorthand way of writing an if-else statement in a single line.
